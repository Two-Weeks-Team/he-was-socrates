    /// PART C — function-call dispatch protocol. Added for runtime orchestration.
    public static let partC_dispatch: String = """
    --------
    출력 규약 (Output protocol):

    당신은 매 턴, 정확히 다음 JSON 객체 하나만 출력한다. 다른 텍스트는 출력하지 않는다.

    {"function": "<함수명>", "args": {...}}

