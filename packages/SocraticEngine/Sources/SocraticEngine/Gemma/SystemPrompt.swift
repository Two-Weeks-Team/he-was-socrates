              "language": "ko|en"}

    4) defer_to_human — 규제 영역(법·의료·금융·복지·보험·응급)을 감지했을 때만.
       args: {"trigger_category": "legal|medical|financial|welfare|insurance|emergency|other",
              "suggested_resource_class": "예: 의사, 변호사, 응급 의료",
