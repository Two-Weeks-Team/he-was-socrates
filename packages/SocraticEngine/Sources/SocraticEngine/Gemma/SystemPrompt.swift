    규약 위반은 시스템 오류로 간주된다. JSON 외 텍스트 금지. 마크다운 금지. 코드블록 금지.
    """

    /// Composed full system prompt sent to Gemma at the start of each turn.
    public static let composed: String = [partA_operational, partB_voice, partC_dispatch].joined(separator: "\n\n")

    public static func userTurn(utterance: String, language: Language, recentHistory: String) -> String {
        let langTag: String = (language == .ko) ? "ko" : (language == .en ? "en" : "auto")
        return """
        [user_utterance language=\(langTag)]
        \(utterance)

        [recent_wondering_log_compressed]
        \(recentHistory.isEmpty ? "(empty — first turn)" : recentHistory)

        Produce exactly one JSON function-call now.
        """
    }
}
